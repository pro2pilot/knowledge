#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const { LOCK_POLICY } = require('./lib/lock-policy');

function parseArgs(argv) {
  const args = { outDir: null };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--out-dir') args.outDir = argv[++index] || null;
    else if (argv[index].startsWith('--out-dir=')) args.outDir = argv[index].slice(10);
  }
  return args;
}

function inventory() {
  return Object.entries(LOCK_POLICY.locks).sort(([left], [right]) => left.localeCompare(right)).map(([lockName, definition]) => ({
    lock_name: lockName,
    root_kinds: [...definition.root_kinds],
    resource_mode: definition.resource_id || 'fixed',
    consumers: [...(definition.consumers || [])].sort(),
    installed_runtime: definition.root_kinds.some((kind) => LOCK_POLICY.root_kinds[kind]?.public === true),
    inspected_by_install_check: definition.root_kinds.some((kind) => ['state', 'project'].includes(kind))
  }));
}

function markdown(entries) {
  const lines = [
    '# Lock consumer inventory',
    '',
    'Generated from `.knowledge/tools/lib/lock-policy.js`. Do not edit this file manually.',
    '',
    '| Lock | Root kinds | Resource mode | Consumers | Installed runtime | Install-check |',
    '| --- | --- | --- | --- | --- | --- |'
  ];
  for (const entry of entries) {
    lines.push(`| \`${entry.lock_name}\` | ${entry.root_kinds.join(', ')} | ${entry.resource_mode} | ${entry.consumers.length ? entry.consumers.map((item) => `\`${item}\``).join(', ') : '—'} | ${entry.installed_runtime ? 'yes' : 'no'} | ${entry.inspected_by_install_check ? 'yes' : 'no'} |`);
  }
  lines.push('');
  return lines.join('\n');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const outDir = path.resolve(args.outDir || path.join(__dirname, '..', 'docs', 'release', '3.3.0', 'project-lock-inspection-rc40'));
  const entries = inventory();
  const report = { schema_version: 'knowledge-lock-consumer-inventory.v1', generated_at: new Date().toISOString(), source: 'tools/lib/lock-policy.js', locks: entries };
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'LOCK-CONSUMER-INVENTORY.json'), `${JSON.stringify(report, null, 2)}\n`, 'utf8');
  fs.writeFileSync(path.join(outDir, 'LOCK-CONSUMER-INVENTORY.md'), markdown(entries), 'utf8');
  process.stdout.write(`${JSON.stringify({ status: 'pass', output_dir: outDir, locks: entries.length }, null, 2)}\n`);
}

if (require.main === module) main();
module.exports = { inventory, markdown, main };
